_TEXT_BLOCK_TYPES = frozenset({"text", "input_text", "output_text"})


def _resolve_message_text(content: object) -> str:
    # heartbeat-filter.ts resolveMessageText: string content, or the text blocks of a content
    # array concatenated without a separator (thinking blocks and other blocks add no text).
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    parts: list[str] = []
    for block in content:
        if not isinstance(block, dict) or "type" not in block:
            continue
        if block.get("type") not in _TEXT_BLOCK_TYPES:
            continue
        text = block.get("text")
        if isinstance(text, str):
            parts.append(text)
    return "".join(parts)


def _matches_heartbeat_prompt_text(text: str, prompt: str | None) -> bool:
    normalized = js_trim(prompt) if isinstance(prompt, str) else ""
    return bool(normalized) and (text == normalized or text.startswith(f"{normalized}\n"))


def is_heartbeat_user_message(
    message: Mapping[str, object],
    heartbeat_prompt: str | None = None,
    *,
    runtime_identity: RuntimeIdentity = MEMORY_CORE_RUNTIME_IDENTITY,
) -> bool:
    """True for a user row that is a heartbeat prompt, not a real user message.

    Port of ``isHeartbeatUserMessage``: an internal-wake transcript row
    (``runtime_identity.internal_wake_transcript_prompts``: the heartbeat poll, and in compat
    mode the exec, cron and session-event rows), also after a ``message``-tool delivery hint;
    the given ``heartbeat_prompt``, the ``heartbeat_respond`` prompts, each alone or followed by
    a newline; and due-task prompts with a known completion line.
    """
    if message.get("role") != "user":
        return False
    trimmed = js_trim(_resolve_message_text(message.get("content")))
    if not trimmed:
        return False
    transcript_prompts = runtime_identity.internal_wake_transcript_prompts
    normalized_prompt = js_trim(heartbeat_prompt) if isinstance(heartbeat_prompt, str) else ""
    if trimmed in transcript_prompts:
        return True
    if any(trimmed.startswith(hint) for hint in MESSAGE_TOOL_DELIVERY_HINTS) and any(
        trimmed.endswith(prompt) for prompt in transcript_prompts
    ):
        return True
    if _matches_heartbeat_prompt_text(trimmed, normalized_prompt):
        return True
    if _matches_heartbeat_prompt_text(trimmed, HEARTBEAT_RESPONSE_TOOL_PROMPT):
        return True
    if normalized_prompt and _matches_heartbeat_prompt_text(
        trimmed, resolve_heartbeat_prompt_for_response_tool(normalized_prompt)
    ):
        return True
    return trimmed.startswith(HEARTBEAT_TASK_PROMPT_PREFIX) and any(
        completion in trimmed for completion in HEARTBEAT_TASK_PROMPT_COMPLETIONS
    )
