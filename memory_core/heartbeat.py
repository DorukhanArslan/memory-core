@dataclass(frozen=True)
class HeartbeatScheduledTask:
    """A due automation job handed to the heartbeat turn (``HeartbeatScheduledTask``,
    ``src/infra/heartbeat-wake-contracts.ts``): its job id, name and prompt."""

    job_id: str
    name: str
    prompt: str


def _infer_wake_source(reason: str | None) -> str | None:
    # heartbeat-wake-policy.ts inferHeartbeatWakeSourceFromReason
    trimmed = js_trim(reason or "")
    if trimmed == "exec-event":
        return "exec-event"
    if trimmed.startswith("cron:"):
        return "cron"
    if trimmed == "wake" or trimmed.startswith("hook:"):
        return "hook"
    if trimmed.startswith("acp:spawn:"):
        return "acp-spawn"
    if trimmed.startswith("session-state:"):
        return "session-state"
    return None


def resolve_heartbeat_wake_flags(
    source: str | None = None, reason: str | None = None
) -> tuple[bool, bool, bool]:
    """``resolveHeartbeatWakePayloadFlags``: (exec-event wake, cron wake, wake payload)."""
    resolved = source or _infer_wake_source(reason)
    trimmed_reason = js_trim(reason or "")
    return (
        resolved == "exec-event",
        resolved == "cron",
        resolved
        in ("hook", "acp-spawn", "session-state", "background-task", "background-task-blocked")
        or trimmed_reason == "wake",
    )


@dataclass(frozen=True)
class HeartbeatPreflight:
    """The monitor-scratch gate of one heartbeat run (``resolveHeartbeatPreflight``).

    ``skip_reason`` is ``empty-heartbeat-file`` for effectively empty scratch or
    ``no-pending-event`` for an exec-event wake with nothing to handle; no model call follows.
    ``scratch_content`` is the scratch given to the prompt: ``None`` without scratch and in
    bypass scopes (cron, exec and wake-payload runs never see the monitor instructions).
    """

    skip_reason: str | None
    scratch_content: str | None
    scratch_revision: int | None
    bypasses_scratch: bool


def _scratch_parts(scratch: HeartbeatScratchState | str | None) -> tuple[str | None, int | None]:
    if scratch is None:
        return None, None
    if isinstance(scratch, str):
        return scratch, None
    return scratch.content, scratch.current_revision


def resolve_heartbeat_preflight(
    scratch: HeartbeatScratchState | str | None,
    *,
    scheduled_tasks: Sequence[HeartbeatScheduledTask] = (),
    source: str | None = None,
    reason: str | None = None,
) -> HeartbeatPreflight:
    """Port of ``resolveHeartbeatPreflight`` for a host with no queued system events.

    ``scratch`` is the agent's monitor scratch (a state from a
    :class:`~memory_core.heartbeat_scratch.HeartbeatScratchStore`, its text, or ``None``).
    Scheduled tasks always run (cron owns their due-ness), missing scratch runs the generic
    prompt, effectively empty scratch skips. ``source``/``reason`` describe the wake like
    upstream's: ``cron``, ``exec-event`` and wake payloads (``hook``, ``reason="wake"``, ...)
    bypass the scratch.
    """
    is_exec, is_cron, is_wake_payload = resolve_heartbeat_wake_flags(source, reason)
    content, revision = _scratch_parts(scratch)
    bypass = is_exec or is_cron or is_wake_payload
    shown = None if bypass else content
    if is_exec and not scheduled_tasks:
        # No pending exec-completion event exists in memory-core (no system-event queue).
        return HeartbeatPreflight(HEARTBEAT_SKIP_NO_PENDING_EVENT, shown, revision, bypass)
    if bypass or scheduled_tasks or content is None:
        return HeartbeatPreflight(None, shown, revision, bypass)
    if is_heartbeat_content_effectively_empty(content):
        return HeartbeatPreflight(HEARTBEAT_SKIP_EMPTY_SCRATCH, shown, revision, bypass)
    return HeartbeatPreflight(None, shown, revision, bypass)


def _append_heartbeat_scratch(prompt: str, scratch_content: str | None) -> str:
    # heartbeat-runner-prompt.ts appendHeartbeatScratch
    if not scratch_content:
        return prompt
    directives = js_trim(scratch_content)
    if not directives or directives in prompt:
        return prompt
    return HEARTBEAT_SCRATCH_PROMPT.format(prompt=prompt, directives=directives)


def build_heartbeat_run_prompt(
    *,
    scheduled_tasks: Sequence[HeartbeatScheduledTask] = (),
    scratch_content: str | None = None,
    prompt: str | None = None,
    use_response_tool: bool = False,
) -> str:
    """The heartbeat user prompt (``resolveHeartbeatRunPrompt`` without system events).

    Due tasks are listed as ``- <name>: <prompt>`` under ``Run the following periodic tasks
    ...`` with a ``NO_REPLY`` (or ``heartbeat_respond``) completion line; otherwise the
    configured ``prompt`` (default ``HEARTBEAT_PROMPT``) is used. The monitor scratch follows
    under ``Heartbeat monitor scratch:`` unless the prompt already contains it.
    ``use_response_tool`` selects the ``heartbeat_respond`` wording (upstream:
    ``messages.visibleReplies`` is ``message_tool``).
    """
    if scheduled_tasks:
        task_list = "\n".join(
            HEARTBEAT_TASK_LINE.format(name=task.name, prompt=task.prompt) for task in scheduled_tasks
        )
        completion = (
            HEARTBEAT_TASKS_RESPONSE_TOOL_COMPLETION
            if use_response_tool
            else HEARTBEAT_TASKS_COMPLETION
        )
        task_prompt = HEARTBEAT_TASKS_PROMPT.format(task_list=task_list, completion=completion)
        return _append_heartbeat_scratch(task_prompt, scratch_content)
    base = (
        resolve_heartbeat_prompt_for_response_tool(prompt)
        if use_response_tool
        else resolve_heartbeat_prompt(prompt)
    )
    return _append_heartbeat_scratch(base, scratch_content)


def normalize_inbound_text_newlines(text: str) -> str:
    """``normalizeInboundTextNewlines`` (``src/auto-reply/reply/inbound-text.ts``): CRLF and
    CR become LF, as ``finalizeInboundContext`` does to the Body the model receives."""
    return text.replace("\r\n", "\n").replace("\r", "\n")


@dataclass(frozen=True)
class HeartbeatTurn:
    """Inputs of one heartbeat turn, or the reason it is skipped.

    ``message`` is the user message for the model: ``prompt`` plus the two current-time lines,
    with CRLF and CR turned into LF like upstream's inbound context (``None`` when skipped). The host records ``HEARTBEAT_TRANSCRIPT_PROMPT`` as the transcript
    row, runs the turn with memory flush disabled (``memory_core.memory_flush`` ``is_heartbeat``),
    reads the reply with :func:`decide_heartbeat_reply` and records the run of every due job
    (:func:`memory_core.automation.record_automation_job_run`).
    """

    skip_reason: str | None
    prompt: str | None
    message: str | None
    scheduled_tasks: tuple[HeartbeatScheduledTask, ...]
    scratch_content: str | None
    scratch_revision: int | None
    uses_response_tool: bool


def prepare_heartbeat_turn(
    *,
    now_ms: int | float,
    scratch: HeartbeatScratchState | str | None = None,
    scheduled_tasks: Sequence[HeartbeatScheduledTask] = (),
    prompt: str | None = None,
    use_response_tool: bool = False,
    source: str | None = None,
    reason: str | None = None,
    timezone: str = "UTC",
) -> HeartbeatTurn:
    """Preflight and prompt of one heartbeat turn the host has decided to run now.

    Mirrors ``resolveHeartbeatWakeStage`` (scheduled tasks sorted by job id), the preflight,
    ``resolveHeartbeatRunPrompt`` and the Body of ``runHeartbeatOnce``
    (``appendCronStyleCurrentTimeLine`` in ``timezone``, UTC by default, then the inbound
    newline normalization). The Current time line is always 24-hour (upstream's ``auto``
    format follows the host OS).
    """
    tasks = tuple(sorted(scheduled_tasks, key=lambda task: locale_sort_key(task.job_id)))
    preflight = resolve_heartbeat_preflight(
        scratch, scheduled_tasks=tasks, source=source, reason=reason
    )
    if preflight.skip_reason:
        return HeartbeatTurn(
            skip_reason=preflight.skip_reason,
            prompt=None,
            message=None,
            scheduled_tasks=tasks,
            scratch_content=preflight.scratch_content,
            scratch_revision=preflight.scratch_revision,
            uses_response_tool=False,
        )
    turn_prompt = build_heartbeat_run_prompt(
        scheduled_tasks=tasks,
        scratch_content=preflight.scratch_content,
        prompt=prompt,
        use_response_tool=use_response_tool,
    )
    return HeartbeatTurn(
        skip_reason=None,
        prompt=turn_prompt,
        message=normalize_inbound_text_newlines(
            append_cron_style_current_time_line(turn_prompt, now_ms=now_ms, timezone=timezone)
        ),
        scheduled_tasks=tasks,
        scratch_content=preflight.scratch_content,
        scratch_revision=preflight.scratch_revision,
        uses_response_tool=use_response_tool,
    )


