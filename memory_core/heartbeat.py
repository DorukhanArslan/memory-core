def _silent_exact_re(token: str) -> re.Pattern[str]:
    escaped = re.escape(token)
    return re.compile(f"^{_SP}*{escaped}(?:{_SP}+{escaped})*{_SP}*\\Z", _JS_I)


def _is_unicode_punctuation(char: str) -> bool:
    return unicodedata.category(char).startswith("P")


def _strip_edge_punctuation(text: str) -> str:
    # tokens.ts stripEdgePunctuation: /^\p{P}+/u and a trailing \p{P}+ run.
    start = 0
    while start < len(text) and _is_unicode_punctuation(text[start]):
        start += 1
    end = len(text)
    while end > 0 and _is_unicode_punctuation(text[end - 1]):
        end -= 1
    return text[start:end]


def is_silent_reply_text(text: str | None, token: str = SILENT_REPLY_TOKEN) -> bool:
    """``isSilentReplyText``: the token alone (repeats and edge punctuation allowed)."""
    if not text:
        return False
    exact = _silent_exact_re(token)
    return bool(exact.match(text) or exact.match(_strip_edge_punctuation(js_trim(text))))


def _is_silent_reply_json_string_text(text: str, token: str) -> bool:
    trimmed = js_trim(text)
    if not trimmed.startswith('"') or not trimmed.endswith('"') or token not in trimmed:
        return False
    try:
        parsed = json.loads(trimmed)
    except ValueError:
        return False
    return isinstance(parsed, str) and js_trim(parsed) == token


def _is_silent_reply_envelope_text(text: str, token: str) -> bool:
    trimmed = js_trim(text)
    if not trimmed or not trimmed.startswith("{") or not trimmed.endswith("}") or token not in trimmed:
        return False
    try:
        parsed = json.loads(trimmed)
    except ValueError:
        return False
    return (
        isinstance(parsed, dict)
        and list(parsed) == ["action"]
        and isinstance(parsed["action"], str)
        and js_trim(parsed["action"]) == token
    )


def _strip_final_silent_token(text: str, token: str) -> str | None:
    pattern = re.compile(f"(?:^|[{_S}*.]){re.escape(token)}{_SP}*\\Z", _JS_I)
    stripped = js_trim(pattern.sub("", text, count=1))
    return None if stripped == js_trim(text) else stripped


def _has_silent_intent_final_silent_token(text: str, token: str) -> bool:
    without = _strip_final_silent_token(text, token)
    if without is None:
        return False
    return not without or bool(_SILENT_INTENT_TEXT_RE.match(without))


def _has_plain_reasoning_final_silent_token(text: str, token: str) -> bool:
    without = _strip_final_silent_token(text, token)
    if without is None:
        return False
    if not without or _SILENT_INTENT_TEXT_RE.match(without):
        return True
    lines = [js_trim(line) for line in _CRLF_SPLIT_RE.split(without)]
    lines = [line for line in lines if line]
    final_line = lines[-1] if lines else None
    previous = "\n".join(lines[:-1])
    return bool(
        final_line
        and _SILENT_INTENT_TEXT_RE.match(final_line)
        and previous
        and not _SUBSTANTIVE_ANSWER_CUE_RE.search(previous)
    ) or bool(_BARE_REASONING_PLACEHOLDER_RE.match(without))


def _is_reasoning_prefixed_silent_reply_text(text: str, token: str) -> bool:
    trimmed = js_trim(text)
    if not trimmed:
        return False
    without_blocks = trimmed
    while True:
        after = _TAGGED_REASONING_PREFIX_RE.sub("", without_blocks, count=1)
        if after == without_blocks:
            break
        without_blocks = after
    if without_blocks != trimmed:
        return is_silent_reply_text(without_blocks, token) or _has_silent_intent_final_silent_token(
            without_blocks, token
        )
    if _OPEN_REASONING_PREFIX_RE.match(trimmed):
        without_open = _OPEN_REASONING_PREFIX_RE.sub("", trimmed, count=1)
        return is_silent_reply_text(without_open, token) or _has_plain_reasoning_final_silent_token(
            without_open, token
        )
    if not _PLAIN_REASONING_PREFIX_RE.match(trimmed):
        return False
    without_plain = _PLAIN_REASONING_PREFIX_RE.sub("", trimmed, count=1)
    return is_silent_reply_text(without_plain, token) or _has_plain_reasoning_final_silent_token(
        without_plain, token
    )


def is_silent_reply_payload_text(text: str | None, token: str = SILENT_REPLY_TOKEN) -> bool:
    """``isSilentReplyPayloadText``: a token-only, JSON-string, ``{"action": ...}`` envelope or
    reasoning-prefixed silent reply (the canonical quiet heartbeat answer is ``NO_REPLY``)."""
    if not text:
        return False
    return (
        is_silent_reply_text(text, token)
        or _is_silent_reply_json_string_text(text, token)
        or _is_silent_reply_envelope_text(text, token)
        or _is_reasoning_prefixed_silent_reply_text(text, token)
    )


def is_heartbeat_acknowledgement_text(
    text: str | None, max_ack_chars: int | float = DEFAULT_HEARTBEAT_ACK_MAX_CHARS
) -> bool:
    """``isHeartbeatAcknowledgementText``: a silent reply or a legacy ``HEARTBEAT_OK`` ack."""
    return is_silent_reply_payload_text(text) or strip_heartbeat_token(
        text, mode="heartbeat", max_ack_chars=max_ack_chars
    ).should_skip


# --- reply decision -------------------------------------------------------------------------

_TRAILING_NOTIFY_FALSE_RE = re.compile(
    "(?:^|[\\r\\n])[ \\t]*notify=false[ \\t]*(?:\\r?\\n[ \\t]*)*\\Z", _JS_I
)


def _strip_leading_response_prefix(text: str, response_prefix: str | None) -> str:
    # heartbeat-delivery-normalization.ts stripLeadingHeartbeatResponsePrefix:
    # /^<prefix>(?=$|\s|[\p{P}\p{S}])\s*/iu.
    prefix = js_trim(response_prefix) if response_prefix else ""
    if not prefix:
        return text
    match = re.match(re.escape(prefix), text, re.IGNORECASE)
    if match is None:
        return text
    rest = text[match.end() :]
    if rest and not (rest[0] in JS_WHITESPACE or unicodedata.category(rest[0])[0] in "PS"):
        return text
    return js_trim_start(rest)


def _is_stream_error_placeholder_only(text: str) -> bool:
    remaining = js_trim(text)
    if not remaining:
        return False
    while remaining.startswith(STREAM_ERROR_FALLBACK_TEXT):
        remaining = js_trim_start(remaining[len(STREAM_ERROR_FALLBACK_TEXT) :])
    return not remaining


@dataclass(frozen=True)
class HeartbeatReplyDecision:
    """How the host treats a heartbeat reply (``classifyHeartbeatAgentOutcome``, text path).

    ``deliver`` is ``True`` only for a real alert, whose text is ``text``. Otherwise the run is
    an acknowledgement: ``event_status`` is ``ok-empty`` (no reply content) or ``ok-token``
    (a silent reply, a ``HEARTBEAT_OK`` ack or a short remainder). ``silent`` comes from a
    trailing ``notify=false`` line: a delivered alert goes out without a notification, an
    acknowledgement shows not even the host's OK indicator.
    """

    deliver: bool
    text: str
    event_status: Literal["ok-empty", "ok-token"] | None
    silent: bool

    def to_json(self) -> dict[str, object]:
        if self.deliver:
            return {"kind": "delivery", "text": self.text, "silent": self.silent}
        return {"kind": "ack", "eventStatus": self.event_status, "silent": self.silent}


def decide_heartbeat_reply(
    text: str | None, *, response_prefix: str | None = None
) -> HeartbeatReplyDecision:
    """Decide whether a heartbeat's text reply is delivered (the v2026.9.6 rule).

    Port of ``classifyHeartbeatAgentOutcome`` and ``normalizeHeartbeatReply`` for a text reply
    without tools, media or a run failure: a canonical silent reply (``NO_REPLY``, see
    :func:`is_silent_reply_payload_text`) and a legacy ``HEARTBEAT_OK`` acknowledgement with at
    most 300 characters around it (``DEFAULT_HEARTBEAT_ACK_MAX_CHARS``; the ``ackMaxChars``
    config key is retired) are not delivered; a trailing ``notify=false`` line is dropped and
    marks the run silent. ``response_prefix`` is stripped before the checks and put back in
    front of a delivered alert.
    """
    raw = text if isinstance(text, str) else ""
    if not js_trim(raw):
        return HeartbeatReplyDecision(False, "", "ok-empty", False)
    text_for_strip = _strip_leading_response_prefix(raw, response_prefix)
    is_silent = is_silent_reply_payload_text(text_for_strip)
    stripped = strip_heartbeat_token(
        "" if is_silent else text_for_strip,
        mode="heartbeat",
        max_ack_chars=DEFAULT_HEARTBEAT_ACK_MAX_CHARS,
    )
    notify_match = _TRAILING_NOTIFY_FALSE_RE.search(stripped.text)
    notify_text = js_trim_end(stripped.text[: notify_match.start()]) if notify_match else stripped.text
    silent = bool(notify_match) or is_silent
    placeholder_only = _is_stream_error_placeholder_only(notify_text)
    if stripped.should_skip or placeholder_only:
        should_skip = True
        final_text = ""
    else:
        final_text = "" if placeholder_only else notify_text
        prefix = response_prefix
        if prefix and final_text and not final_text.startswith(prefix):
            final_text = f"{prefix} {final_text}"
        should_skip = not js_trim(final_text)
    if should_skip:
        # A canonical quiet reply still honours the host's show-OK setting.
        return HeartbeatReplyDecision(
            False, "", "ok-token", silent and not is_silent_reply_payload_text(raw)
        )
    return HeartbeatReplyDecision(True, final_text, None, silent)


