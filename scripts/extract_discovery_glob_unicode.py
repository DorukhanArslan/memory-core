"""Extract Unicode category facts used by Node 24.16's bundled minimatch."""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
from pathlib import Path
import subprocess
import zlib


PROGRAM = r'''
import fs from 'node:fs';
import { createHash } from 'node:crypto';
if (process.version !== 'v24.16.0' || process.versions.icu !== '78.3' || process.versions.unicode !== '17.0') {
  throw Error('Use the reviewed Node 24.16.0 / ICU 78.3 / Unicode 17.0 category owner');
}
const classes = {
  alnum: String.raw`[\p{L}\p{Nl}\p{Nd}]`, alpha: String.raw`[\p{L}\p{Nl}]`,
  blank: String.raw`[\p{Zs}\t]`, cntrl: String.raw`\p{Cc}`, digit: String.raw`\p{Nd}`,
  graph: String.raw`[^\p{Z}\p{C}]`, lower: String.raw`\p{Ll}`, print: String.raw`\p{C}`,
  punct: String.raw`\p{P}`, space: String.raw`[\p{Z}\t\r\n\v\f]`, upper: String.raw`\p{Lu}`,
  word: String.raw`[\p{L}\p{Nl}\p{Nd}\p{Pc}]`,
};
const ranges = {};
for (const [name, source] of Object.entries(classes)) {
  const pattern = new RegExp(source, 'u'), matches = [];
  let start = null;
  for (let value = 0; value <= 0x10ffff; value++) {
    if (pattern.test(String.fromCodePoint(value))) { if (start === null) start = value; }
    else if (start !== null) { matches.push([start, value - 1]); start = null; }
  }
  if (start !== null) matches.push([start, 0x10ffff]);
  ranges[name] = matches;
}
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
console.log(JSON.stringify({ranges, provenance: {
  nodeVersion: process.version, icuVersion: process.versions.icu, unicodeVersion: process.versions.unicode,
  nodeBinarySha256: digest(fs.readFileSync(process.execPath)),
  minimatchSourceSha256: digest(process.binding('natives')['internal/deps/minimatch/index']),
}}));
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--node', required=True)
    parser.add_argument('--output', type=Path, default=Path('memory_core/_memory_glob_unicode.py'))
    args = parser.parse_args()
    result = subprocess.run([args.node, '--input-type=module', '-e', PROGRAM], check=True,
                            capture_output=True, text=True)
    extracted = json.loads(result.stdout)
    ranges, provenance = extracted['ranges'], extracted['provenance']
    payload = json.dumps(ranges, separators=(',', ':'), ensure_ascii=True).encode()
    compressed = base64.b85encode(zlib.compress(payload, 9))
    content = ('"""Unicode category ranges from Node 24.16.0 / ICU 78.3 / Unicode 17.0.\n\n'
               'Generated by scripts/extract_discovery_glob_unicode.py; data facts only.\n'
               'Unicode data: Copyright 2016-2025 Unicode, Inc.; see LICENSE.unicode.\n'
               'Original bundled matcher: internal/deps/minimatch/index.\n'
               'The print class intentionally follows the bundled owner\'s category C.\n'
               f'Uncompressed JSON SHA-256: {hashlib.sha256(payload).hexdigest()}\n"""\n\n'
               'import base64\nimport json\nimport zlib\n\n')
    content += 'PROVENANCE = ' + repr(provenance) + '\n\n_DATA = (\n'
    content += ''.join(f'    {compressed[index:index + 90]!r}\n' for index in range(0, len(compressed), 90))
    content += ')\n\nRANGES = json.loads(zlib.decompress(base64.b85decode(_DATA)))\n'
    args.output.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
