def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--node', required=True)
    parser.add_argument('--output', type=Path, default=Path(PACKAGE_NAME) / '_memory_scan_error_facts.py')
    args = parser.parse_args()
    result = subprocess.run([args.node, '--input-type=module', '-e', PROGRAM], check=True, capture_output=True, text=True)
    facts = json.loads(result.stdout)
    content = ('"""Node 24.16.0 Linux system-error message facts for memory discovery.\n\n'
               'Generated by scripts/extract_scan_io_errors.py from node:util.getSystemErrorMap.\n'
               'No runtime Node dependency or general engine-equivalence claim.\n\n' + NOTICE + '\n"""\n\n')
    content += 'PROVENANCE = ' + repr(facts['provenance']) + '\n\nMESSAGES = {\n'
    content += ''.join(f'    {key!r}: {value!r},\n' for key, value in facts['messages'].items()) + '}\n'
    args.output.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
