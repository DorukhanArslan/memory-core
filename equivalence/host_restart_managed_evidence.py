"""Real managed search-bootstrap, live notice, publication and close custody."""
import json
from pathlib import Path

from equivalence.host_restart_evidence import require
from equivalence.host_restart_publication_evidence import _validate_publication_capture
from equivalence.promotion_apply_family import differences


def _settled(snapshot):
    require(snapshot["activeOperations"] == 0 and not snapshot["operationJournalTruncated"]
            and not snapshot["repairJournalTruncated"], "The managed owner lost physical operation or journal custody")
    require(all(operation["state"] == "completed" for operation in snapshot["operations"]), "The actual managed owner did not settle its observed operations")


def validate_capture(case, raw, result, *, native):
    base = _validate_publication_capture(case, raw, result, native=native, managed=True)
    policy = case["input"]["policy"]
    require(policy["indexLifecycle"] == "managed" and policy["runtimeIdentity"] == "openclaw-compatible", "Managed lifecycle or compatibility identity changed")
    if native:
        return {**base, "originalManagedRuntimeExecuted": True}
    for child in raw["phases"]:
        phase = child["observation"]["raw"]
        for opened in phase["opens"]:
            owner = opened["managedLifecycleAfterOpen"]
            _settled(owner)
            expected = "missing" if opened["sessionName"] in {"writer", "isolated"} else "valid"
            require(opened["managedStatusAfterOpen"]["custom"]["indexIdentity"]["status"] == expected
                    and owner["repairCount"] == 0 and not owner["closed"], "Managed construction silently repaired or closed the index")
        for turn in phase["turns"]:
            for call in turn["toolCalls"]:
                before, after = call["managedLifecycleBefore"], call["managedLifecycleAfter"]
                _settled(before)
                _settled(after)
                if call["name"] != "memory_search":
                    continue
                payload = call["observed"]["payload"]
                if turn["session"] == "isolated":
                    require(after["repairCount"] == before["repairCount"] + 1, "Cold search skipped its genuine repair request")
                    repair = after["repairs"][-1]
                    require(repair["reason"] == "search-bootstrap" and repair["force"] is True
                            and repair["state"] == "completed" and repair["before"]["identity"]["status"] == "missing"
                            and not repair["before"]["hasContent"] and repair["after"]["identity"]["status"] == "valid",
                            "The cold notice was not generated by an actual missing-index repair")
                    notice = after["automaticRebuildNotice"]
                    require(repair["noticeSequenceBefore"] == before["automaticRebuildNotice"]["sequence"]
                            and repair["noticeSequenceAfter"] == notice["sequence"] == repair["noticeSequenceBefore"] + 1
                            and payload["warning"] == notice["warning"], "The tool warning did not come from its live repair transition")
                    parents = [operation for operation in after["operations"] if operation["id"] == repair["searchOperationId"]]
                    require(len(parents) == 1 and parents[0]["name"] == "search" and parents[0]["query"] == call["arguments"]["query"], "Repair is detached from its actual model tool query")
                    publications = [operation for operation in after["operations"] if operation["parentOperationId"] == repair["searchOperationId"] and operation["name"] == "reindex"]
                    require(len(publications) == 1, "Cold search did not own exactly one original SQLite publication")
                    publication = publications[0]
                    require(publication["request"] == {"force": True} and publication["returned"] == repair["returned"]
                            and publication["revisionAfter"] == publication["revisionBefore"] + 1
                            and publication["after"]["identity"]["status"] == "valid", "Repair receipt is not bound to its real subsequent SQLite revision")
                else:
                    require(after["repairCount"] == before["repairCount"] and "warning" not in payload, "Warm search replayed or invented a cold repair notice")
        require(len(phase["closeReceipts"]) == len(phase["opens"]), "The host failed to close every managed owner")
        for closed in phase["closeReceipts"]:
            _settled(closed["before"])
            _settled(closed["after"])
            require(not closed["before"]["closed"] and closed["returnedNone"]
                    and closed["after"]["closed"] and not closed["after"]["closing"], "The managed host did not join actual physical work before close")
    return {**base, "managedColdBootstrapCustodyPassed": True}


def replay_case(case, directory):
    directory = Path(directory)
    native = json.loads((directory / "evidence/native-raw.json").read_text())[0]
    sdk = json.loads((directory / "evidence/python-raw.json").read_text())[0]
    original = json.loads((directory / "stdout.json").read_text())["result"]
    implementation = json.loads((directory / "sdk-output.json").read_text())
    return {"native": validate_capture(case, native, original, native=True),
            "sdk": validate_capture(case, sdk, implementation, native=False),
            "structuralCustodyPassed": True, "differences": differences(original, implementation),
            "acceptancePointsAwarded": 0}
