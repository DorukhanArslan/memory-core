"""Heartbeat turn inputs and reply handling, in the v2026.9.6 shape.

At v2026.9.6 the heartbeat runner never reads a workspace file (3e2b3ea4d5e, #112967;
07e3855b465, #113131): an agent's standing instructions are its heartbeat monitor scratch
(:mod:`memory_core.heartbeat_scratch`), recurring work is automation jobs (:mod:`memory_core.automation`;
b23c7bd0f84, #113165) that reach the heartbeat turn as scheduled tasks, and the ``## Heartbeats``
system-prompt section is gone (6a1dedb00c2, #129642). Ported here:

- constants and prompt resolution (``src/auto-reply/heartbeat.ts``, ``tokens.ts``): the default
  prompt ends with ``NO_REPLY``; the ``heartbeat_respond`` prompt carries the fallback
  instructions; the texts come from ``memory_core/_heartbeat_constants.py`` (generated by
  ``scripts/extract_upstream_constants.py``); the brand-bearing transcript row goes through
  :class:`~memory_core.runtime_identity.RuntimeIdentity`;
- the preflight (``resolveHeartbeatPreflight``, ``src/infra/heartbeat-runner-prompt.ts``):
  effectively empty scratch skips with ``empty-heartbeat-file``, no scratch runs the generic
  prompt, due scheduled tasks always run, wake payloads, cron and exec wakes bypass the scratch;
- the run prompt (``resolveHeartbeatRunPrompt``): due tasks as ``Run the following periodic
  tasks ...`` or the configured prompt, then ``Heartbeat monitor scratch:``, and the Body's
  current-time lines (``appendCronStyleCurrentTimeLine``, ``heartbeat-runner-run.ts``);
- the reply decision (``classifyHeartbeatAgentOutcome`` / ``normalizeHeartbeatReply``,
  ``src/infra/heartbeat-delivery-normalization.ts``): canonical silent replies
  (``isSilentReplyPayloadText``, ``tokens.ts``), legacy ``HEARTBEAT_OK`` at the start or end
  with the 300-character rule (``stripHeartbeatToken``), a trailing ``notify=false`` line and
  the stream-error placeholder;
- the cadence helpers (``parseDurationMs``, ``resolveHeartbeatIntervalMs``) and the transcript
  filter (``isHeartbeatUserMessage``, ``src/auto-reply/heartbeat-filter.ts``).

Scope: the host owns scheduling (the monitor cadence, active hours, busy and in-flight
deferral, wake coalescing), the model call, delivery (targets, visibility, typing, duplicate
suppression) and the session store. memory-core decides what the heartbeat turn sends, whether it
is skipped and how its reply is read; it never starts a timer. Typical host flow::

    store = FileAutomationStore(root)
    due = due_automation_jobs(store.list_jobs(agent_id="main"), now_ms)
    turn = prepare_heartbeat_turn(
        scratch=store.read_scratch("main"),
        scheduled_tasks=heartbeat_scheduled_tasks(due),
        now_ms=now_ms,
    )
    if turn.skip_reason is None:
        reply = run_model(turn.message)          # memory flush off for heartbeats
        decision = decide_heartbeat_reply(reply)
        if decision.deliver:
            deliver(decision.text)
    in_turn = {task.job_id for task in turn.scheduled_tasks}
    store.save_jobs(
        [record_automation_job_run(job, started_at_ms=now_ms) for job in due if job.id in in_turn]
    )

Only heartbeat-task jobs become scheduled tasks
(:func:`~memory_core.automation.heartbeat_scheduled_tasks`), so only they are recorded; any other
due job (a main-session ``systemEvent`` job that is not a heartbeat task, which upstream runs
through ``executeMainSessionCronJob``) is the host's to run.

Not ported: pending system events (exec completions, cron events, session notices, so an
exec-event wake without scheduled tasks is always skipped as ``no-pending-event``), the
``heartbeat_respond`` tool and its ``scratch`` argument, response-prefix typing, media replies,
isolated ``:heartbeat`` sessions and the agent-run failure copy.
"""

