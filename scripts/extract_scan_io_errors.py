"""Extract Node 24 Linux system-error message facts for the scan IO bridge."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess

from memory_core.project_name import PACKAGE_NAME

PROGRAM = r'''
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { getSystemErrorMap } from 'node:util';
if (process.version !== 'v24.16.0' || process.platform !== 'linux') throw Error('Use the reviewed Node 24.16.0 Linux owner');
const digest = (value) => createHash('sha256').update(value).digest('hex');
const messages = Object.fromEntries([...getSystemErrorMap()].map(([, [code, message]]) => [code, message]).sort());
console.log(JSON.stringify({messages, provenance: {
  nodeVersion: process.version, platform: process.platform,
  nodeBinarySha256: digest(fs.readFileSync(process.execPath)),
  internalErrorsSourceSha256: digest(process.binding('natives')['internal/errors']),
  messageFactsSha256: digest(JSON.stringify(messages)),
}}));
'''

