"""Retire a workspace TOOLS.md into the ``## Tools`` section of AGENTS.md.

v2026.9.6 dropped TOOLS.md from the workspace bootstrap set (669db2968fc, #113966): local tool
notes live in AGENTS.md ``## Tools``, and ``openclaw doctor --fix`` migrates an old file. This
module ports that migration for a memory-core workspace root:

- ``shouldMergeToolsMd`` (``src/commands/doctor-tools-md-migration-content.ts``): empty and
  whitespace-only files and upstream's three stock templates are not merged;
- ``rewriteLegacyAgentsToolsGuidance`` (``src/commands/doctor-tools-md-migration-guidance.ts``)
  plus ``ensureLocalNotesHeading``: AGENTS.md lines that point at TOOLS.md are rewritten;
- ``mergeToolsMdIntoAgentsMd``, ``findToolsSection`` and ``appendWithSpacing``
  (``src/commands/doctor-tools-md-migration.ts``): customised content is appended verbatim
  under ``### Local notes (migrated from TOOLS.md)`` at the end of the ``## Tools`` section
  (a new ``## Tools`` section when AGENTS.md has none), idempotently;
- ``maybeMigrateToolsMd`` with ``shouldRepair``: the original is archived first (verified by
  SHA-256), AGENTS.md is written atomically only when it changes, and TOOLS.md is removed only
  after its content and identity are re-checked against the archived snapshot;
- ``collectToolsMdMigrationFindings``: the read-only doctor health findings
  (:func:`tools_md_migration_findings`), so a host sees that a leftover TOOLS.md is no longer
  loaded; :func:`memory_core.bootstrap.build_workspace_context` reports them as
  ``migration_findings``.

The upstream strings come from ``memory_core/bootstrap/_tools_md_constants.py``, generated by
``scripts/extract_upstream_constants.py``. Deviations: the archive lives under the workspace,
``<root>/.memory-core/backups/tools-md-migration/<agent>-<sha256>.md`` (upstream:
``<OPENCLAW_STATE_DIR>/backups/tools-md-migration/``; memory-core keeps its state in ``.memory-core``);
every missing directory of that path is created ``0o700`` like upstream's recursive
``fs.mkdir``. Warnings follow upstream's ``formatErrorMessage`` shape (the message, then each
``cause`` and its error code, joined by `` | ``), but OS error texts are Python's, not Node's,
and the secret redaction of that formatter is not applied (migration errors carry paths only).
Findings name one agent per call (upstream checks every agent sharing the workspace against
its own ``bootstrapMaxChars``), and their fix hint names :data:`MIGRATE_TOOLS_MD_COMMAND`
instead of ``openclaw doctor --fix``; the limit finding keeps upstream's config key names. The
doctor preview note is not ported.
"""

from __future__ import annotations

import errno
import hashlib
import os
import re
import shutil
import stat
import time
from dataclasses import dataclass
from pathlib import Path

from typing import Literal

from memory_core.bootstrap._bootstrap_constants import DEFAULT_BOOTSTRAP_MAX_CHARS
from memory_core.bootstrap._js import JS_SPACE, js_iu_keyword_pattern, js_trim, utf16_len
from memory_core.bootstrap._tools_md_constants import (
    LEGACY_AGENTS_TOOLS_GUIDANCE_REWRITES,
    LEGACY_TOOLS_DEV_FALLBACK,
    LEGACY_TOOLS_DEV_MD_TEMPLATE,
    LEGACY_TOOLS_MD_TEMPLATE,
    MIGRATED_SUBSECTION_HEADING,
    TOOLS_MD_MIGRATION_CHECK_ID,
    TOOLS_MD_MIGRATION_FINDINGS,
    TOOLS_MD_MIGRATION_FIX_HINT,
)
from memory_core.bootstrap.budget import resolve_bootstrap_char_limit
from memory_core.bootstrap.layout import AGENTS_FILENAME, TOOLS_FILENAME

TOOLS_MD_ARCHIVE_PARTS = (".memory-core", "backups", "tools-md-migration")
# Named in the findings' fix hint where upstream names `openclaw doctor --fix`.
MIGRATE_TOOLS_MD_COMMAND = "memory_core.bootstrap.migrate_tools_md()"
LEGACY_TOOLS_MD_REQUIREMENT = "legacy-tools-md"
TOOLS_MD_MERGED_BOOTSTRAP_LIMIT_REQUIREMENT = "tools-md-merged-bootstrap-limit"
TOOLS_MD_MIGRATION_BLOCKED_REQUIREMENT = "tools-md-migration-blocked"
_FINDINGS = {
    requirement: (severity, message) for requirement, severity, message in TOOLS_MD_MIGRATION_FINDINGS
}
_BETA_TOOLS_PREFIX = f"{TOOLS_FILENAME}.doctor-importing-"
_BETA_AGENTS_PREFIX = f"{AGENTS_FILENAME}.doctor-backup-"
_WRITING_INFIX = ".doctor-writing-"

# JavaScript regex semantics: `.` stops at every line terminator, `$` is end of input.
_LINE_RE = re.compile("[^\n\r\u2028\u2029]*(?:\n|\\Z)")
_FENCE_RE = re.compile(f"^{JS_SPACE}*(`{{3,}}|~{{3,}})")
_CLOSING_FENCE_RE = re.compile(f"^{JS_SPACE}*(`{{3,}}|~{{3,}}){JS_SPACE}*\\Z")
_HEADING_RE = re.compile(f"^(#{{1,6}}){JS_SPACE}+(.+?){JS_SPACE}*#*{JS_SPACE}*\\Z")
_LOCAL_NOTES_RE = re.compile(
    "(?:^|(?<=[\n\r\u2028\u2029]))###"
    f"{JS_SPACE}+{js_iu_keyword_pattern('Local notes')}(?:{JS_SPACE}|\\Z)"
)


def should_merge_tools_md(content: str) -> bool:
    """Port of ``shouldMergeToolsMd``: not blank and not one of upstream's stock templates."""
    return bool(js_trim(content)) and content not in (
        LEGACY_TOOLS_MD_TEMPLATE,
        LEGACY_TOOLS_DEV_MD_TEMPLATE,
        LEGACY_TOOLS_DEV_FALLBACK,
    )


def rewrite_legacy_agents_tools_guidance_lines(content: str) -> str:
    """Port of ``rewriteLegacyAgentsToolsGuidance`` (the guidance module): replace every pair."""
    rewritten = content
    for legacy, current in LEGACY_AGENTS_TOOLS_GUIDANCE_REWRITES:
        rewritten = rewritten.replace(legacy, current)
    return rewritten


def _find_tools_section(content: str) -> tuple[int, int] | None:
    """Port of ``findToolsSection``: ``(heading_end, insert_at)`` of ``## Tools``, or None."""
    offset = 0
    inside_tools = False
    heading_end = 0
    fence: tuple[str, int] | None = None
    for match in _LINE_RE.finditer(content):
        line_with_ending = match.group(0)
        if line_with_ending == "":
            continue
        line = line_with_ending[:-1] if line_with_ending.endswith("\n") else line_with_ending
        fence_match = _FENCE_RE.match(line)
        closing_match = _CLOSING_FENCE_RE.match(line)
        fence_run = fence_match.group(1) if fence_match else None
        closing_run = closing_match.group(1) if closing_match else None
        if fence_run and not fence:
            fence = (fence_run[0], len(fence_run))
        elif closing_run and fence and closing_run[0] == fence[0] and len(closing_run) >= fence[1]:
            fence = None
        elif not fence:
            heading = _HEADING_RE.match(line)
            if heading:
                depth = len(heading.group(1))
                if inside_tools and depth <= 2:
                    return heading_end, offset
                if depth == 2 and js_trim(heading.group(2)).lower() == "tools":
                    inside_tools = True
                    heading_end = offset + len(line_with_ending)
        offset += len(line_with_ending)
    return (heading_end, len(content)) if inside_tools else None


def _ensure_local_notes_heading(content: str) -> str:
    section = _find_tools_section(content)
    if section is None:
        return content
    heading_end, insert_at = section
    if _LOCAL_NOTES_RE.search(content[heading_end:insert_at]):
        return content
    return f"{content[:heading_end]}\n### Local notes\n{content[heading_end:]}"


def rewrite_legacy_agents_tools_guidance(content: str) -> str:
    """The migration's ``rewriteLegacyAgentsToolsGuidance``: rewrite, then add ``### Local notes``."""
    rewritten = rewrite_legacy_agents_tools_guidance_lines(content)
    return content if rewritten == content else _ensure_local_notes_heading(rewritten)


def _append_with_spacing(before: str, addition: str, after: str = "") -> str:
    if not before:
        prefix = ""
    elif before.endswith("\n\n"):
        prefix = ""
    elif before.endswith("\n"):
        prefix = "\n"
    else:
        prefix = "\n\n"
    if not after:
        suffix = ""
    elif addition.endswith("\n\n"):
        suffix = ""
    elif addition.endswith("\n"):
        suffix = "\n"
    else:
        suffix = "\n\n"
    return f"{before}{prefix}{addition}{suffix}{after}"


def merge_tools_md_into_agents_md(agents_content: str, tools_content: str) -> str:
    """Port of ``mergeToolsMdIntoAgentsMd`` (idempotent for already-merged content)."""
    merged = rewrite_legacy_agents_tools_guidance(agents_content)
    if MIGRATED_SUBSECTION_HEADING in merged:
        if tools_content in merged:
            return merged
        insert_at = merged.index(MIGRATED_SUBSECTION_HEADING) + len(MIGRATED_SUBSECTION_HEADING)
        return _append_with_spacing(merged[:insert_at], tools_content, merged[insert_at:])
    block = f"{MIGRATED_SUBSECTION_HEADING}\n\n{tools_content}"
    section = _find_tools_section(merged)
    if section is None:
        return _append_with_spacing(merged, f"## Tools\n\n{block}")
    _heading_end, insert_at = section
    return _append_with_spacing(merged[:insert_at], block, merged[insert_at:])


class ToolsMdMigrationError(RuntimeError):
    pass


@dataclass(frozen=True)
class _Snapshot:
    content: str
    stat: os.stat_result | None


def _read_snapshot(path: Path, label: str, *, allow_missing: bool = False) -> _Snapshot:
    """Port of ``readMigrationFileSnapshot``: an unlinked regular file, opened no-follow."""
    try:
        info = os.lstat(path)
    except FileNotFoundError:
        if allow_missing:
            return _Snapshot("", None)
        raise
    if not stat.S_ISREG(info.st_mode) or info.st_nlink > 1:
        raise ToolsMdMigrationError(
            f"{label} must be an unlinked regular file for automatic migration"
        )
    fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    try:
        opened = os.fstat(fd)
        if (
            not stat.S_ISREG(opened.st_mode)
            or opened.st_nlink != 1
            or (opened.st_dev, opened.st_ino) != (info.st_dev, info.st_ino)
        ):
            raise ToolsMdMigrationError(f"{label} changed while opening it for migration")
        chunks: list[bytes] = []
        while True:
            chunk = os.read(fd, 1 << 16)
            if not chunk:
                break
            chunks.append(chunk)
        content = b"".join(chunks).decode("utf-8", errors="replace")
        current = os.lstat(path)
        if (current.st_dev, current.st_ino) != (opened.st_dev, opened.st_ino):
            raise ToolsMdMigrationError(f"{label} changed while opening it for migration")
        return _Snapshot(content, opened)
    finally:
        os.close(fd)


def _sha256(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8", errors="surrogatepass")).hexdigest()


def _shorten_home_path(value: str) -> str:
    home = os.path.expanduser("~")
    if home and home != "~" and (value == home or value.startswith(home.rstrip(os.sep) + os.sep)):
        return "~" + value[len(home.rstrip(os.sep)) :]
    return value


def _temp_path(target: Path) -> Path:
    return Path(f"{target}{_WRITING_INFIX}{os.getpid()}-{int(time.time() * 1000)}")


def _format_error_message(exc: BaseException) -> str:
    """``formatErrorMessage`` (``packages/normalization-core/src/error-coercion.ts``) for the
    ``__cause__`` chain: the message, then each cause's message (skipped when the text already
    contains it) and its errno name, joined by `` | ``; secret redaction is not ported."""
    formatted = str(exc) or type(exc).__name__
    seen = {formatted}

    def append(message: str | None) -> None:
        nonlocal formatted
        if message and message not in seen:
            formatted += f" | {message}"
            seen.add(message)

    visited = {id(exc)}
    cause = exc.__cause__
    while cause is not None and id(cause) not in visited:
        visited.add(id(cause))
        message = str(cause)
        if message and message in formatted:
            seen.add(message)
        else:
            append(message)
        if isinstance(cause, OSError) and cause.errno is not None:
            append(errno.errorcode.get(cause.errno))
        cause = cause.__cause__
    return formatted


def _make_private_dirs(path: Path) -> None:
    """``fs.mkdir(path, {recursive: true, mode: 0o700})``: every missing level gets ``0o700``."""
    missing: list[Path] = []
    current = path
    while not os.path.lexists(current):
        missing.append(current)
        if current.parent == current:
            break
        current = current.parent
    for directory in reversed(missing):
        try:
            os.mkdir(directory, 0o700)
        except FileExistsError:
            if not directory.is_dir():
                raise
    if not path.is_dir():
        os.mkdir(path, 0o700)  # raises the error upstream's mkdir reports (EEXIST, ENOTDIR)


def _archive_source(archive_dir: Path, agent_id: str, content: str, digest: str) -> Path:
    safe_agent_id = re.sub(r"[^A-Za-z0-9._-]+", "-", agent_id)
    archive = archive_dir / f"{safe_agent_id}-{digest}.md"
    _make_private_dirs(archive_dir)
    temp = _temp_path(archive)
    try:
        fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            os.write(fd, content.encode("utf-8", errors="surrogatepass"))
            os.fsync(fd)
        finally:
            os.close(fd)
        try:
            # publishFileNoClobber "link-or-copy": never replace an existing archive.
            os.link(temp, archive)
        except FileExistsError:
            raise
        except OSError:
            with open(temp, "rb") as source, open(archive, "xb") as target:
                shutil.copyfileobj(source, target)
        os.unlink(temp)
    except FileExistsError as exc:
        temp.unlink(missing_ok=True)
        if _sha256(archive.read_bytes().decode("utf-8", errors="replace")) != digest:
            # Upstream: new Error(..., {cause: error}); the cause reaches the warning text.
            raise ToolsMdMigrationError(
                f"TOOLS.md migration archive collision at {archive}"
            ) from exc
    except BaseException:
        temp.unlink(missing_ok=True)
        raise
    return archive


def _recover_interrupted_agents_write(agents_path: Path) -> None:
    prefix = f"{agents_path.name}{_WRITING_INFIX}"
    try:
        entries = os.listdir(agents_path.parent)
    except OSError:
        entries = []
    for entry in entries:
        if not entry.startswith(prefix):
            continue
        temp = agents_path.parent / entry
        info = os.lstat(temp)
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise ToolsMdMigrationError(
                f"interrupted AGENTS.md write must be an unlinked regular file: {temp}"
            )
        temp.unlink()


def _write_agents_atomically(agents_path: Path, expected: str, content: str) -> None:
    snapshot = _read_snapshot(agents_path, "AGENTS.md", allow_missing=True)
    if snapshot.content != expected:
        raise ToolsMdMigrationError("AGENTS.md changed during TOOLS.md migration")
    mode = stat.S_IMODE(snapshot.stat.st_mode) if snapshot.stat is not None else 0o600
    temp = _temp_path(agents_path)
    try:
        fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
        try:
            os.write(fd, content.encode("utf-8", errors="surrogatepass"))
            os.fsync(fd)
        finally:
            os.close(fd)
        current = _read_snapshot(agents_path, "AGENTS.md", allow_missing=True)
        same_identity = (
            (current.stat is None and snapshot.stat is None)
            or (
                current.stat is not None
                and snapshot.stat is not None
                and (current.stat.st_dev, current.stat.st_ino)
                == (snapshot.stat.st_dev, snapshot.stat.st_ino)
            )
        )
        if current.content != expected or not same_identity:
            raise ToolsMdMigrationError("AGENTS.md changed during TOOLS.md migration")
        os.replace(temp, agents_path)
    except BaseException:
        temp.unlink(missing_ok=True)
        raise


@dataclass(frozen=True)
class ToolsMdMigrationResult:
    """Outcome of :func:`migrate_tools_md` (upstream ``{changes, warnings}`` plus detail).

    ``merged`` is True when customised content went into AGENTS.md, False when an untouched
    template or blank file was only archived and removed, None when nothing ran.
    """

    changes: tuple[str, ...]
    warnings: tuple[str, ...]
    archive_path: str | None = None
    merged: bool | None = None


def tools_md_archive_dir(root: str | os.PathLike[str]) -> Path:
    return Path(os.path.abspath(os.path.expanduser(os.fspath(root)))).joinpath(
        *TOOLS_MD_ARCHIVE_PARTS
    )


def _read_tools_md(workspace: Path) -> _Snapshot | None:
    """Port of ``readToolsMd``: refuse beta artifacts, then snapshot TOOLS.md (None if absent)."""
    try:
        entries = os.listdir(workspace)
    except OSError:
        entries = []
    beta = [
        entry
        for entry in entries
        if entry.startswith(_BETA_TOOLS_PREFIX) or entry.startswith(_BETA_AGENTS_PREFIX)
    ]
    if beta:
        raise ToolsMdMigrationError(
            f"Interrupted v2026.7.2-beta.5 migration artifact(s) left untouched: "
            f"{', '.join(beta)}. Restore the desired file manually before rerunning doctor."
        )
    source = _read_snapshot(workspace / TOOLS_FILENAME, "TOOLS.md", allow_missing=True)
    return None if source.stat is None else source


@dataclass(frozen=True)
class ToolsMdMigrationFinding:
    """One doctor ``HealthFinding`` of ``collectToolsMdMigrationFindings``."""

    check_id: str
    severity: Literal["warning", "error"]
    message: str
    path: str
    target: str
    requirement: str
    fix_hint: str

    def to_json(self) -> dict[str, str]:
        return {
            "checkId": self.check_id,
            "severity": self.severity,
            "message": self.message,
            "path": self.path,
            "target": self.target,
            "requirement": self.requirement,
            "fixHint": self.fix_hint,
        }


def _finding(
    requirement: str, *, agent_id: str, path: Path, **fields: object
) -> ToolsMdMigrationFinding:
    severity, message = _FINDINGS[requirement]
    return ToolsMdMigrationFinding(
        check_id=TOOLS_MD_MIGRATION_CHECK_ID,
        severity=severity,  # type: ignore[arg-type]
        message=message.format(agent_id=agent_id, **fields),
        path=str(path),
        target=agent_id,
        requirement=requirement,
        fix_hint=TOOLS_MD_MIGRATION_FIX_HINT.format(command=MIGRATE_TOOLS_MD_COMMAND),
    )


def tools_md_migration_findings(
    root: str | os.PathLike[str],
    *,
    agent_id: str = "main",
    bootstrap_max_chars: int | None = DEFAULT_BOOTSTRAP_MAX_CHARS,
) -> tuple[ToolsMdMigrationFinding, ...]:
    """Port of ``collectToolsMdMigrationFindings`` for one agent's workspace (read-only).

    A TOOLS.md at ``root`` gives a ``legacy-tools-md`` warning (upstream no longer loads it).
    When its content would be merged, a ``tools-md-merged-bootstrap-limit`` warning follows if
    the merged AGENTS.md (UTF-16 length, like upstream) exceeds ``bootstrap_max_chars``
    (``None`` or ``<= 0``: 20,000, like ``resolveBootstrapMaxChars``). A file the migration
    would refuse (beta artifacts, a symlink or hard link, an unreadable AGENTS.md) adds a
    ``tools-md-migration-blocked`` error. Nothing is written.
    """
    workspace = Path(os.path.abspath(os.path.expanduser(os.fspath(root))))
    tools_path = workspace / TOOLS_FILENAME
    agents_path = workspace / AGENTS_FILENAME
    findings: list[ToolsMdMigrationFinding] = []
    try:
        source = _read_tools_md(workspace)
        if source is not None:
            findings.append(
                _finding(LEGACY_TOOLS_MD_REQUIREMENT, agent_id=agent_id, path=tools_path)
            )
            if should_merge_tools_md(source.content):
                agents = _read_snapshot(agents_path, "AGENTS.md", allow_missing=True).content
                merged_chars = utf16_len(merge_tools_md_into_agents_md(agents, source.content))
                limit = resolve_bootstrap_char_limit(
                    bootstrap_max_chars, DEFAULT_BOOTSTRAP_MAX_CHARS
                )
                if merged_chars > limit:
                    findings.append(
                        _finding(
                            TOOLS_MD_MERGED_BOOTSTRAP_LIMIT_REQUIREMENT,
                            agent_id=agent_id,
                            path=agents_path,
                            merged_chars=merged_chars,
                            bootstrap_max_chars=limit,
                        )
                    )
    except Exception as exc:  # upstream reports every failure as a blocked finding
        findings.append(
            _finding(
                TOOLS_MD_MIGRATION_BLOCKED_REQUIREMENT,
                agent_id=agent_id,
                path=tools_path,
                error=_format_error_message(exc),
            )
        )
    return tuple(findings)


def migrate_tools_md(
    root: str | os.PathLike[str], *, agent_id: str = "main"
) -> ToolsMdMigrationResult:
    """Merge ``<root>/TOOLS.md`` into ``<root>/AGENTS.md`` like ``maybeMigrateToolsMd``.

    No TOOLS.md: nothing happens. Otherwise the original is archived under
    ``<root>/.memory-core/backups/tools-md-migration/<agent_id>-<sha256>.md``, customised content
    (:func:`should_merge_tools_md`) is merged under ``## Tools`` /
    ``### Local notes (migrated from TOOLS.md)`` (an untouched template only gets the AGENTS.md
    guidance rewrite), and TOOLS.md is removed after its SHA-256 and file identity are checked
    again. Any failure leaves TOOLS.md in place and is reported in ``warnings``; rerunning
    converges (an interrupted AGENTS.md temp write is cleaned up, already-merged content is not
    appended twice).
    """
    workspace = Path(os.path.abspath(os.path.expanduser(os.fspath(root))))
    tools_path = workspace / TOOLS_FILENAME
    agents_path = workspace / AGENTS_FILENAME
    try:
        source = _read_tools_md(workspace)
        if source is None or source.stat is None:
            return ToolsMdMigrationResult((), ())
        digest = _sha256(source.content)
        should_merge = should_merge_tools_md(source.content)
        archive = _archive_source(tools_md_archive_dir(workspace), agent_id, source.content, digest)
        _recover_interrupted_agents_write(agents_path)
        agents_content = _read_snapshot(agents_path, "AGENTS.md", allow_missing=True).content
        merged = (
            merge_tools_md_into_agents_md(agents_content, source.content)
            if should_merge
            else rewrite_legacy_agents_tools_guidance(agents_content)
        )
        if merged != agents_content:
            _write_agents_atomically(agents_path, agents_content, merged)
            if _read_snapshot(agents_path, "AGENTS.md").content != merged:
                raise ToolsMdMigrationError(
                    "AGENTS.md changed after TOOLS.md migration was written"
                )
        current = _read_snapshot(tools_path, "TOOLS.md")
        if _sha256(current.content) != digest:
            raise ToolsMdMigrationError("TOOLS.md changed during migration")
        now = os.lstat(tools_path)
        if (
            current.stat is None
            or (now.st_dev, now.st_ino) != (current.stat.st_dev, current.stat.st_ino)
            or (now.st_dev, now.st_ino) != (source.stat.st_dev, source.stat.st_ino)
        ):
            raise ToolsMdMigrationError("TOOLS.md changed during migration")
        os.unlink(tools_path)
    except Exception as exc:  # upstream collects every failure as a warning
        return ToolsMdMigrationResult(
            (), (f'Agent "{agent_id}" TOOLS.md was not migrated: {_format_error_message(exc)}',)
        )
    shown = _shorten_home_path(str(tools_path))
    change = (
        f"Merged {shown} into AGENTS.md and archived the original."
        if should_merge
        else f"Removed untouched {shown} after archiving it."
    )
    return ToolsMdMigrationResult((change,), (), str(archive), should_merge)
